/**
 * Get audio examples for a single category.
 * @param {string} category - Category key (e.g. 'delay', 'chorus')
 * @returns {object|null} The category object or null if not found
 */
export function getExamplesForCategory(category) {
  return audioExamples[category] || null;
}

/**
 * Get audio examples for multiple categories.
 * @param {string[]} categories - Array of category keys
 * @returns {object[]} Array of matching category objects (missing keys are filtered out)
 */
export function getExamplesForCategories(categories) {
  return categories.map(cat => audioExamples[cat]).filter(Boolean);
}
